// 本文欄の下から出す「AIへの手直しの注文」の語彙。
// コンポーネント側に置くと Fast Refresh が効かなくなるので、ここに分ける。

/**
 * 本文欄の下から「これを手直しして」と頼むときの注文。
 * message が空なら入力欄を開いて自分で書いてもらうだけ、入っていればそのまま生成へ進む。
 * nonce は、同じ内容の注文を続けて出しても届くようにするための連番。
 */
export interface AiEditRequest {
  message: string
  nonce: number
}

/**
 * 本文のすぐ下に並べる、押すだけで通る手直しの注文。
 * 本文を書き終えた人がAIに頼みたいのはたいていこの数種類で、
 * そのたびに上の欄へ指示を打ち込ませるほどのことではない。
 */
export const AI_EDIT_PRESETS = [
  { label: '整える', message: 'いまの本文の内容はそのままに、読みやすく整えて、そのまま投稿できる形にする' },
  { label: '短く', message: 'いまの本文を、結論から短く言い切る形にする' },
  { label: 'やわらかく', message: 'いまの本文を、話しかけるようなやわらかい文体にする' },
  { label: '出だしを強く', message: 'いまの本文の内容はそのままに、最初の一文で目が留まる書き出しにする' },
] as const

/** 指示が空のまま頼まれたときの読み替え先。本文があるなら「これを整えて」で用は足りる。 */
export const DEFAULT_EDIT_MESSAGE = AI_EDIT_PRESETS[0].message
